"""Phase 1 — Data Analysis & Exploration for IBM Telco Customer Churn.

Writes figures to reports/figures/ and a write-up to reports/phase1_eda.md.
Run from telco-churn/: ./.venv/bin/python src/eda.py  (venv is at repo root ../.venv)
"""
from __future__ import annotations
import os, textwrap
from pathlib import Path
import numpy as np
import pandas as pd
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import seaborn as sns
from scipy import stats
import warnings

warnings.filterwarnings("ignore")
sns.set_theme(style="whitegrid")
DATA = Path("data/telco_churn.csv")
FIG = Path("reports/figures"); FIG.mkdir(parents=True, exist_ok=True)
OUT = Path("reports/phase1_eda.md")

md: list[str] = []
def h(s): md.append(f"\n## {s}\n"); print(f"\n=== {s} ===")
def p(s=""): md.append(str(s)); print(s)
def savefig(name):
    plt.tight_layout(); plt.savefig(FIG / name, dpi=110, bbox_inches="tight"); plt.close()
    md.append(f"\n![{name}](figures/{name})\n")

df = pd.read_csv(DATA)
df["TotalCharges"] = pd.to_numeric(df["TotalCharges"], errors="coerce")  # blanks -> NaN
y = (df["Churn"] == "Yes").astype(int)

md.append("# Phase 1 — Data Analysis & Exploration\n")
md.append("IBM Telco Customer Churn. Auto-generated by `src/eda.py`.\n")

# ---------------- 1a overview
h("1a. Data overview")
p(f"- shape: {df.shape[0]} customers x {df.shape[1]} columns")
cat_cols = [c for c in df.columns if not pd.api.types.is_numeric_dtype(df[c])
            and c not in ("customerID", "Churn")]
num_cols = ["tenure", "MonthlyCharges", "TotalCharges", "SeniorCitizen"]
p(f"- categorical features: {len(cat_cols)} | numeric: {len(num_cols)}")
p(f"- ID column `customerID` ({df['customerID'].nunique()} unique) → dropped from features.")

# ---------------- 1b target
h("1b. Target: churn balance")
p(f"- churn rate: {y.mean()*100:.1f}% (Yes={int(y.sum())}, No={int((1-y).sum())}) — class imbalance.")
plt.figure(figsize=(4.5, 4))
ax = sns.countplot(x=df["Churn"], order=["No", "Yes"], palette=["#4C72B0", "#C44E52"])
for pt in ax.patches:
    ax.annotate(int(pt.get_height()), (pt.get_x()+pt.get_width()/2, pt.get_height()), ha="center", va="bottom")
plt.title("Churn distribution"); plt.xlabel("")
savefig("churn_distribution.png")

# ---------------- 1c data quality
h("1c. Data quality")
n_blank = df["TotalCharges"].isna().sum()
p(f"- **`TotalCharges` had {n_blank} blank strings** → coerced to NaN. All correspond to `tenure == 0`:")
p(f"  tenure of blank-TotalCharges rows: {sorted(df.loc[df['TotalCharges'].isna(),'tenure'].unique())} "
  "(brand-new customers, no bill yet). Impute 0 in cleaning.")
p(f"- `SeniorCitizen` is already 0/1 encoded. Service columns use 'No internet service' / "
  "'No phone service' as a distinct third level.")

# ---------------- 1d churn by categorical
h("1d. Churn rate by categorical driver")
def churn_rate_plot(cols, fname, title):
    n = len(cols); ncol = 3; nrow = int(np.ceil(n/ncol))
    plt.figure(figsize=(5*ncol, 3.4*nrow))
    for i, c in enumerate(cols, 1):
        plt.subplot(nrow, ncol, i)
        rate = df.groupby(c)["Churn"].apply(lambda s: (s == "Yes").mean()).sort_values()
        sns.barplot(x=rate.values*100, y=rate.index, palette="rocket")
        plt.axvline(y.mean()*100, color="k", ls="--", lw=1)
        plt.title(c, fontsize=10); plt.xlabel("churn %")
    plt.suptitle(title, y=1.02)
    savefig(fname)

churn_rate_plot(["Contract", "InternetService", "PaymentMethod",
                 "OnlineSecurity", "TechSupport", "PaperlessBilling"],
                "churn_by_category.png", "Churn rate by key categorical features (dashed = base rate)")
p("Dashed line = overall base rate (26.5%). Month-to-month contracts, fiber-optic internet, "
  "electronic-check payment, and lack of online security / tech support show markedly higher churn.")

# ---------------- 1e numeric distributions
h("1e. Numeric features vs churn")
plt.figure(figsize=(14, 3.6))
for i, c in enumerate(["tenure", "MonthlyCharges", "TotalCharges"], 1):
    plt.subplot(1, 3, i)
    for k, col in [(0, "#4C72B0"), (1, "#C44E52")]:
        sns.kdeplot(df.loc[y == k, c].dropna(), fill=True, alpha=.4, color=col,
                    label=("Churn" if k else "Stay"))
    plt.title(c, fontsize=10); plt.xlabel(""); plt.legend()
plt.suptitle("Numeric feature distributions by churn", y=1.03)
savefig("numeric_by_churn.png")
p("Churners concentrate at **low tenure** and **high monthly charges**; long-tenure customers rarely churn.")

# tenure buckets
df["_tenure_bucket"] = pd.cut(df["tenure"], [-1, 6, 12, 24, 48, 72],
                              labels=["0-6", "7-12", "13-24", "25-48", "49-72"])
plt.figure(figsize=(6.5, 4))
rate = df.groupby("_tenure_bucket")["Churn"].apply(lambda s: (s == "Yes").mean())
sns.barplot(x=rate.index, y=rate.values*100, palette="viridis")
plt.axhline(y.mean()*100, color="k", ls="--", lw=1)
plt.title("Churn rate by tenure bucket (months)"); plt.ylabel("churn %"); plt.xlabel("tenure")
savefig("churn_by_tenure.png")

# ---------------- 1f associations
h("1f. Feature–target association")
def cramers_v(x, yy):
    ct = pd.crosstab(x, yy); chi2 = stats.chi2_contingency(ct)[0]
    n = ct.values.sum(); r, k = ct.shape
    return np.sqrt(chi2 / (n * (min(r, k) - 1))) if min(r, k) > 1 else np.nan
assoc = [(c, cramers_v(df[c], y)) for c in cat_cols]
assoc = pd.DataFrame(assoc, columns=["feature", "cramers_v"]).sort_values("cramers_v", ascending=False)
p("**Categorical features vs churn (Cramér's V):**\n"); p(assoc.to_string(index=False))
plt.figure(figsize=(7, 5))
sns.barplot(data=assoc, y="feature", x="cramers_v", palette="mako")
plt.title("Categorical association with churn (Cramér's V)"); plt.xlabel("Cramér's V"); plt.ylabel("")
savefig("assoc_categorical.png")

num_assoc = []
for c in ["tenure", "MonthlyCharges", "TotalCharges"]:
    a = df.loc[y == 1, c].dropna(); b = df.loc[y == 0, c].dropna()
    u, pv = stats.mannwhitneyu(a, b)
    num_assoc.append((c, round(a.mean(), 1), round(b.mean(), 1), f"{pv:.1e}"))
p("\n**Numeric features (Mann–Whitney, churn vs stay means):**\n")
p(pd.DataFrame(num_assoc, columns=["feature", "mean_churn", "mean_stay", "p"]).to_string(index=False))

# ---------------- 1g hypotheses
h("1g. Hypotheses & takeaways")
p(textwrap.dedent("""\
1. Contract type is the dominant driver: month-to-month customers churn far more than 1/2-year contracts.
2. Short tenure → high churn; risk drops sharply after the first year (retention/onboarding effect).
3. Fiber-optic + electronic-check + paperless billing mark a high-churn segment (price-sensitive, less sticky).
4. Add-on services (OnlineSecurity, TechSupport) reduce churn → "stickiness" features.
5. High monthly charges raise churn, but high *total* charges (a proxy for tenure) lower it — engineer
   charges-per-tenure and a service-count feature.
6. Metric: churn is imbalanced (26.5%) → optimize/report ROC-AUC and PR-AUC, not raw accuracy.
"""))

OUT.write_text("\n".join(md))
print(f"\nWrote {OUT} and figures to {FIG}")
